type StrokeName = keyof typeof paths;
type FillName = keyof typeof filledPaths;

export function Icon({
  name,
  className = "size-4",
  brand = false,
}: Readonly<{
  name: StrokeName | FillName;
  className?: string;
  brand?: boolean;
}>) {
  const gradientId = useId().replace(/:/g, "-");
  if (name in filledPaths) {
    const fillName = name as FillName;
    if (brand && name === "instagram") {
      return (
        <svg aria-hidden="true" className={className} viewBox="0 0 24 24">
          <defs>
            <linearGradient id={`ig-${gradientId}`} x1="0%" y1="100%" x2="100%" y2="0%">
              {gradientStops.instagram.map((color, i) => (
                <stop key={color} offset={`${(i / (gradientStops.instagram.length - 1)) * 100}%`} stopColor={color} />
              ))}
            </linearGradient>
          </defs>
          <path fill={`url(#ig-${gradientId})`} d={filledPaths[fillName]} />
        </svg>
      );
    }
    const fill = brand && brandFills[fillName] ? brandFills[fillName] : "currentColor";
    return (
      <svg aria-hidden="true" className={className} viewBox="0 0 24 24" fill={fill}>
        <path d={filledPaths[fillName]} />
      </svg>
    );
  }
  return (
    <svg aria-hidden="true" className={className} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.5" strokeLinecap="round" strokeLinejoin="round">
      <path d={paths[name as StrokeName]} />
    </svg>
  );
}
